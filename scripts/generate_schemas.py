"""Regenerate BigQuery schemas and SQL DDL from the validated application models."""

import json
from pathlib import Path

from src.models import Profile, Result, Rule

ROOT = Path(__file__).resolve().parents[1]


def fields(model) -> list[dict]:
    schema = model.model_json_schema()
    result = []
    for name, definition in schema["properties"].items():
        mode = "NULLABLE"
        if "anyOf" in definition:
            definition = next(item for item in definition["anyOf"] if item.get("type") != "null")
        kind = definition.get("type", "string")
        if kind == "array":
            mode, kind = "REPEATED", "string"
        bq_type = {
            "string": "STRING",
            "integer": "INTEGER",
            "number": "FLOAT",
            "boolean": "BOOLEAN",
            "object": "JSON",
        }[kind]
        if definition.get("format") == "date-time":
            bq_type = "TIMESTAMP"
        result.append({"name": name, "type": bq_type, "mode": mode})
    return result


def main() -> None:
    tables = {
        "notification_profiles": fields(Profile),
        "monitoring_rules": fields(Rule),
        "monitoring_results": fields(Result),
        "monitoring_runs": [
            {"name": name, "type": kind, "mode": mode}
            for name, kind, mode in [
                ("run_id", "STRING", "NULLABLE"),
                ("started_at", "TIMESTAMP", "NULLABLE"),
                ("window_end", "TIMESTAMP", "NULLABLE"),
                ("finished_at", "TIMESTAMP", "NULLABLE"),
                ("status", "STRING", "NULLABLE"),
                ("rule_count", "INTEGER", "NULLABLE"),
                ("problem_count", "INTEGER", "NULLABLE"),
                ("configuration_errors", "STRING", "REPEATED"),
                ("notifications", "STRING", "NULLABLE"),
                ("preview", "BOOLEAN", "NULLABLE"),
            ]
        ],
    }
    destination = ROOT / "sql" / "schemas"
    destination.mkdir(parents=True, exist_ok=True)
    ddl = ["-- Generated by scripts/generate_schemas.py; replace PROJECT_ID and DATASET_ID."]
    for table, schema in tables.items():
        (destination / f"{table}.json").write_text(json.dumps(schema, indent=2) + "\n", "utf-8")
        columns = []
        for item in schema:
            kind = {"INTEGER": "INT64", "FLOAT": "FLOAT64", "BOOLEAN": "BOOL"}.get(
                item["type"],
                item["type"],
            )
            if item["mode"] == "REPEATED":
                kind = f"ARRAY<{kind}>"
            columns.append(f"  {item['name']} {kind}")
        statement = f"CREATE TABLE IF NOT EXISTS `PROJECT_ID.DATASET_ID.{table}` (\n"
        statement += ",\n".join(columns) + "\n)"
        if table == "monitoring_results":
            statement += "\nPARTITION BY DATE(checked_at)\nCLUSTER BY project_id, rule_id, status"
        if table == "monitoring_runs":
            statement += "\nPARTITION BY DATE(started_at)\nCLUSTER BY status"
        ddl.append(statement + ";")
    (ROOT / "sql" / "01_tables.sql").write_text("\n\n".join(ddl) + "\n", "utf-8")


if __name__ == "__main__":
    main()
